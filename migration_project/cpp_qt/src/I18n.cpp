bool I18n::setLanguage(const QString& language) {
    if (!m_texts.contains(language))
        return false;
    m_currentLanguage = language;
    return true;
}

QString I18n::currentLanguage() const {
    return m_currentLanguage;
}

QString I18n::tr(const QString& key, const QVariantHash& args) const {
    const auto& lang = m_texts.value(m_currentLanguage);
    QString text = lang.value(key);
    if (text.isEmpty()) {
        text = m_texts.value(DEFAULT_LANGUAGE).value(key, key);
    }
    if (args.isEmpty())
        return text;

    for (auto it = args.cbegin(); it != args.cend(); ++it) {
        text.replace("{" + it.key() + "}", it.value().toString());
    }
    return text;
}
